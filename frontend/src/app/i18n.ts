export const supportedLanguages = ["fr", "ar"] as const;
export type AppLanguage = (typeof supportedLanguages)[number];
export type AppDirection = "ltr" | "rtl";

export function normalizeLanguage(language?: string): AppLanguage {
  return language?.toLowerCase().startsWith("ar") ? "ar" : "fr";
}

export function getLanguageDirection(language?: string): AppDirection {
  return normalizeLanguage(language) === "ar" ? "rtl" : "ltr";
}

function getInitialLanguage(): AppLanguage {
  if (typeof window === "undefined") return "fr";
  return normalizeLanguage(window.localStorage.getItem("hiveapp-language") ?? undefined);
}

